# Continuous Performance Monitoring Script
# Displays real-time performance metrics in a dashboard-like view

param(
    [string]$BaseUrl = "http://localhost:5299/",
    [int]$RefreshIntervalSeconds = 2
)

function Show-Header {
    Clear-Host
    Write-Host "??????????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
    Write-Host "?       LLM Embedding API - Performance Monitoring Dashboard         ?" -ForegroundColor Cyan
    Write-Host "??????????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
    Write-Host ""
    Write-Host "  Monitoring: $BaseUrl" -ForegroundColor White
    Write-Host "  Refresh: Every $RefreshIntervalSeconds seconds" -ForegroundColor White
    Write-Host "  Press Ctrl+C to stop" -ForegroundColor Yellow
  Write-Host ""
}

function Show-Metric {
    param(
        [string]$Label,
        [string]$Value,
        [string]$Unit = "",
        [string]$Color = "White",
        [double]$Threshold = 0,
        [double]$NumericValue = 0,
        [bool]$UseThreshold = $false
    )
    
    if ($UseThreshold -and $NumericValue -gt $Threshold) {
        $Color = "Red"
    }
    
    $paddedLabel = $Label.PadRight(20)
  Write-Host "  $paddedLabel : " -NoNewline -ForegroundColor Gray
    Write-Host "$Value $Unit" -ForegroundColor $Color
}

function Get-MemoryBar {
    param([double]$MemoryMB, [double]$MaxMemoryMB = 2048)
    
    $percentage = [math]::Min(($MemoryMB / $MaxMemoryMB) * 100, 100)
 $barLength = 40
    $filledLength = [math]::Floor(($percentage / 100) * $barLength)
    $emptyLength = $barLength - $filledLength
    
    $bar = "?" * $filledLength + "?" * $emptyLength
    
    $color = "Green"
    if ($percentage -gt 80) { $color = "Red" }
    elseif ($percentage -gt 60) { $color = "Yellow" }
    
    return @{
        Bar = $bar
        Percentage = [math]::Round($percentage, 1)
        Color = $color
    }
}

function Get-CpuBar {
    param([double]$CpuPercent)
    
    $barLength = 40
    $filledLength = [math]::Floor(($CpuPercent / 100) * $barLength)
    $emptyLength = $barLength - $filledLength
    
    $bar = "?" * $filledLength + "?" * $emptyLength
    
    $color = "Green"
    if ($CpuPercent -gt 80) { $color = "Red" }
    elseif ($CpuPercent -gt 60) { $color = "Yellow" }
    
    return @{
        Bar = $bar
        Percentage = [math]::Round($CpuPercent, 1)
        Color = $color
    }
}

# Check API availability
Write-Host "Checking API availability..." -ForegroundColor Yellow
try {
    $null = Invoke-RestMethod -Uri "$BaseUrl/health" -Method Get -TimeoutSec 5
    Write-Host "? API is accessible" -ForegroundColor Green
    Start-Sleep -Seconds 1
} catch {
    Write-Host "? Cannot connect to API at $BaseUrl" -ForegroundColor Red
    Write-Host "  Please ensure the API is running" -ForegroundColor Red
    exit 1
}

$startTime = Get-Date
$iteration = 0

while ($true) {
    try {
    $iteration++
        $metrics = Invoke-RestMethod -Uri "$BaseUrl/api/metrics/current" -Method Get -ErrorAction Stop
        
        Show-Header
        
  # Runtime Information
        Write-Host "?? Runtime ?????????????????????????????????????????????????????????" -ForegroundColor DarkGray
      $uptime = (Get-Date) - $startTime
  Show-Metric -Label "Uptime" -Value "$($uptime.Hours)h $($uptime.Minutes)m $($uptime.Seconds)s"
        Show-Metric -Label "Timestamp" -Value $metrics.timestamp
     Show-Metric -Label "Samples Collected" -Value $iteration
        Write-Host "????????????????????????????????????????????????????????????????????" -ForegroundColor DarkGray
   Write-Host ""
     
    # CPU Metrics
        Write-Host "?? CPU Usage ???????????????????????????????????????????????????????" -ForegroundColor DarkGray
        $cpuBar = Get-CpuBar -CpuPercent $metrics.cpuUsagePercent
        Show-Metric -Label "Current" -Value $([math]::Round($metrics.cpuUsagePercent, 2)) -Unit "%" `
      -Color $cpuBar.Color -UseThreshold $true -Threshold 80 -NumericValue $metrics.cpuUsagePercent
        Write-Host "  $($cpuBar.Bar) $($cpuBar.Percentage)%" -ForegroundColor $cpuBar.Color
        Show-Metric -Label "Peak" -Value $([math]::Round($metrics.peakCpuPercent, 2)) -Unit "%"
        Show-Metric -Label "Thread Count" -Value $metrics.threadCount
        Write-Host "????????????????????????????????????????????????????????????????????" -ForegroundColor DarkGray
      Write-Host ""
        
        # Memory Metrics
        Write-Host "?? Memory Usage ????????????????????????????????????????????????????" -ForegroundColor DarkGray
        $memBar = Get-MemoryBar -MemoryMB $metrics.workingSetMB
     Show-Metric -Label "Working Set" -Value $([math]::Round($metrics.workingSetMB, 2)) -Unit "MB" `
            -Color $memBar.Color
        Write-Host "  $($memBar.Bar) $($memBar.Percentage)%" -ForegroundColor $memBar.Color
        Show-Metric -Label "Peak Working Set" -Value $([math]::Round($metrics.peakWorkingSetMB, 2)) -Unit "MB" -Color "Yellow"
        Show-Metric -Label "Private Memory" -Value $([math]::Round($metrics.privateMemoryMB, 2)) -Unit "MB"
        Show-Metric -Label "Peak Private" -Value $([math]::Round($metrics.peakPrivateMemoryMB, 2)) -Unit "MB" -Color "Yellow"
   Show-Metric -Label "GC Heap Size" -Value $([math]::Round($metrics.gcHeapSizeMB, 2)) -Unit "MB"
     Write-Host "????????????????????????????????????????????????????????????????????" -ForegroundColor DarkGray
  Write-Host ""
   
 # Garbage Collection
        Write-Host "?? Garbage Collection ??????????????????????????????????????????????" -ForegroundColor DarkGray
    Show-Metric -Label "Gen 0 Collections" -Value $metrics.gen0Collections -Color "Green"
    Show-Metric -Label "Gen 1 Collections" -Value $metrics.gen1Collections -Color "Yellow"
        Show-Metric -Label "Gen 2 Collections" -Value $metrics.gen2Collections -Color "Red"
 Write-Host "????????????????????????????????????????????????????????????????????" -ForegroundColor DarkGray
        Write-Host ""
        
        # System Information
        Write-Host "?? System ??????????????????????????????????????????????????????????" -ForegroundColor DarkGray
        Show-Metric -Label "Handle Count" -Value $metrics.handleCount
      Write-Host "????????????????????????????????????????????????????????????????????" -ForegroundColor DarkGray
        Write-Host ""
        
        # Quick Recommendations
        $recommendedMemoryGB = [math]::Ceiling($metrics.peakWorkingSetMB / 1024 * 1.5 * 2) / 2
  $recommendedCpuCores = [math]::Ceiling(($metrics.peakCpuPercent / 100) * 1.3 * 4) / 4
        $recommendedMemoryGB = [math]::Max(0.5, $recommendedMemoryGB)
    $recommendedCpuCores = [math]::Max(0.5, $recommendedCpuCores)

     Write-Host "?? Azure ACI Recommendations (Based on Current Peaks) ?????????????" -ForegroundColor DarkGray
        Show-Metric -Label "Minimum vCPU" -Value $recommendedCpuCores -Color "Cyan"
        Show-Metric -Label "Minimum Memory" -Value $recommendedMemoryGB -Unit "GB" -Color "Cyan"
        Write-Host "  Note: Run load tests for accurate production recommendations" -ForegroundColor DarkYellow
   Write-Host "????????????????????????????????????????????????????????????????????" -ForegroundColor DarkGray
        Write-Host ""
        
    # Status
        Write-Host "  Status: " -NoNewline -ForegroundColor Gray
        Write-Host "Monitoring Active" -ForegroundColor Green
  Write-Host "  Next update in $RefreshIntervalSeconds seconds..." -ForegroundColor DarkGray
        
        Start-Sleep -Seconds $RefreshIntervalSeconds
      
    } catch {
        Show-Header
        Write-Host ""
        Write-Host "  ? Error collecting metrics" -ForegroundColor Red
        Write-Host "  $($_.Exception.Message)" -ForegroundColor Red
Write-Host ""
        Write-Host "  Retrying in $RefreshIntervalSeconds seconds..." -ForegroundColor Yellow
      Start-Sleep -Seconds $RefreshIntervalSeconds
    }
}
